'use strict';
module.exports = async function smoke(win) {
  const { app, Menu } = require('electron');
  const assert = require('node:assert/strict');
  const fs = require('node:fs');
  const path = require('node:path');
  const output = process.argv.find(arg => arg.startsWith('--smoke-output='))?.slice('--smoke-output='.length) || path.resolve(process.cwd(), 'smoke-results');
  fs.mkdirSync(output, { recursive: true });
  const errors = [];
  win.webContents.on('console-message', (_event, details) => { if (details.level === 'error') errors.push(details.message); });
  const wait = () => new Promise(resolve => setTimeout(resolve, 250));
  const js = script => win.webContents.executeJavaScript(script);
  await wait();
  const report = { packaged: app.isPackaged, version: app.getVersion(), name: app.getName(), checks: [] };
  assert.equal(Menu.getApplicationMenu(), null);
  assert.equal(win.getTitle(), 'GE2340 Model Explorer');
  assert.equal(await js("document.documentElement.classList.contains('desktop-app')"), true);
  assert.equal(await js("document.querySelectorAll('.desktop-controls button').length"), 3);
  assert.equal(await js("typeof require"), 'undefined');
  assert.equal(await js("document.querySelector('#model').value"), 'sgd-classifier');
  assert.equal(await js("document.querySelector('#classification-result').hidden"), false);
  assert.equal(await js("document.querySelector('#regression-result').hidden"), true);
  assert.equal(await js("document.querySelectorAll('#probabilities .prob-row').length"), 5);
  assert.equal(await js("document.querySelector('#metrics .metric-value').textContent"), '42.75%');
  assert.equal(await js("document.querySelector('#result-state').textContent"), 'EXAMPLE DAY');
  assert.equal(await js("document.querySelector('#class-value').textContent"), 'Upper-middle group (B)');
  fs.writeFileSync(path.join(output, 'desktop-classifier.png'), (await win.webContents.capturePage()).toPNG());
  await js("document.querySelector('#hours-0').value='9';document.querySelector('#hours-0').dispatchEvent(new Event('input',{bubbles:true}));document.querySelector('#predict').click()");
  await wait();
  assert.equal(await js("document.querySelector('#result-state').textContent"), 'PREDICTION UPDATED');
  await js("document.querySelector('#reset').click()");
  await wait();
  report.checks.push('classifier default, class probabilities, classifier metrics, input updates and reset');
  await js("document.querySelector('#model').value='linear-regression';document.querySelector('#model').dispatchEvent(new Event('change',{bubbles:true}))");
  await wait();
  assert.equal(await js("document.querySelector('#classification-result').hidden"), true);
  assert.equal(await js("document.querySelector('#regression-result').hidden"), false);
  assert.equal(await js("document.querySelector('#relative-grade').textContent"), 'Middle group (C)');
  assert.equal(await js("document.querySelector('#top-percent').textContent"), 'Top ≈ 42%');
  report.checks.push('custom titlebar and branding; no menu; isolated renderer; initial prediction');
  await js("document.querySelector('#hours-0').value='9';document.querySelector('#hours-0').dispatchEvent(new Event('input',{bubbles:true}));document.querySelector('#predict').click()");
  await wait();
  assert.equal(await js("document.querySelector('#relative-grade').textContent"), 'Upper-middle group (B)');
  assert.equal(await js("document.querySelector('#top-percent').textContent"), 'Top ≈ 23%');
  await js("document.querySelector('#reset').click()");
  await wait();
  report.checks.push('input and prediction updates');
  const image = await win.webContents.capturePage();
  fs.writeFileSync(path.join(output, 'desktop-app.png'), image.toPNG());
  await js("document.querySelector('#window-maximize').click()");
  await wait();
  assert.equal(win.isMaximized(), true);
  assert.equal(await js("document.querySelector('#window-maximize').getAttribute('aria-label')"), 'Restore window');
  await js("document.querySelector('#window-maximize').click()");
  await wait();
  assert.equal(win.isMaximized(), false);
  await js("document.querySelector('#window-minimize').click()");
  await wait();
  assert.equal(win.isMinimized(), true);
  win.restore();
  report.checks.push('custom maximize, restore and minimize controls');
  assert.deepEqual(errors, []);
  report.consoleErrors = errors;
  win.once('closed', () => {
    report.checks.push('custom close control');
    fs.writeFileSync(path.join(output, 'verification.json'), JSON.stringify(report, null, 2));
    console.log('PASS: ' + report.checks.join('; '));
  });
  await js("document.querySelector('#window-close').click()");
};
