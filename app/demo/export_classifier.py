"""Export Jeffrey's fitted classifier after checking the committed experiment results."""
from pathlib import Path
import hashlib
import json
import sys
import tempfile
import numpy as np
import pandas as pd
import sklearn

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'src'))
from run_pipeline import run_classifier, FEATURES, SEED


def export():
    proc = ROOT / 'outputs/processed'
    sets = {s: pd.read_csv(proc / f'{s}_raw.csv') for s in ('train', 'validation', 'test')}
    with tempfile.TemporaryDirectory(prefix='ge2340_classifier_') as temporary:
        output = Path(temporary)
        model = run_classifier(output, proc, sets)
        actual = pd.read_csv(output / 'sgd_classification_metrics.csv')
        expected = pd.read_csv(ROOT / 'outputs/sgd_classification_metrics.csv')
        pd.testing.assert_frame_equal(actual, expected, rtol=1e-12, atol=1e-12)
        for split in sets:
            pd.testing.assert_frame_equal(pd.read_csv(output / f'sgd_confusion_{split}.csv'),
                                          pd.read_csv(ROOT / f'outputs/sgd_confusion_{split}.csv'))
    poly, scaler, clf = (model.named_steps[k] for k in ('poly', 'scaler', 'clf'))
    data = {
        'estimator': 'SGDClassifier', 'multiclass': 'one-vs-rest',
        'features': FEATURES, 'classes': clf.classes_.tolist(), 'powers': poly.powers_.tolist(),
        'mean': scaler.mean_.tolist(), 'scale': scaler.scale_.tolist(),
        'coefficients': clf.coef_.tolist(), 'intercepts': clf.intercept_.tolist(),
        'fitSplit': 'train', 'seed': SEED, 'iterations': int(clf.n_iter_),
        'sklearnVersion': sklearn.__version__,
        'sourceSha256': hashlib.sha256((ROOT / 'src/run_pipeline.py').read_bytes()).hexdigest(),
        'settings': {k: clf.get_params()[k] for k in ('loss', 'penalty', 'l1_ratio', 'alpha', 'learning_rate', 'eta0', 'max_iter', 'tol', 'class_weight')},
        'metrics': {r['split']: {k: float(r[k]) for k in ('accuracy', 'macro_f1', 'balanced_accuracy')} for r in expected.to_dict('records')},
        'baseline': pd.read_csv(ROOT / 'outputs/classification_metrics.csv').query("split == 'test'").iloc[0][['accuracy', 'macro_f1', 'balanced_accuracy']].to_dict()
    }
    raw = json.dumps(data, indent=2, allow_nan=False)
    (ROOT / 'outputs/sgd_classifier_model.json').write_text(raw+'\n', encoding='utf-8')
    (ROOT / 'app/demo/classifier-data.js').write_text('/* Generated by export_classifier.py. */\nglobalThis.GE2340_CLASSIFIER = '+raw+';\n', encoding='utf-8')
    frames = []
    for split, rows in sets.items():
        probs = model.predict_proba(rows[FEATURES])
        frame = pd.DataFrame({'row_id': rows.row_id, 'split': split, 'prediction': model.predict(rows[FEATURES])})
        for i, label in enumerate(clf.classes_): frame['probability_'+label] = probs[:, i]
        frames.append(frame)
    pd.concat(frames, ignore_index=True).to_csv(ROOT / 'outputs/sgd_predictions.csv', index=False)
    # Extra valid schedules check browser inference beyond the saved observations.
    rng = np.random.default_rng(SEED)
    inputs = np.vstack([np.eye(5)*24, np.full((1,5),24/5), rng.dirichlet(np.ones(5), 64)*24])
    X = pd.DataFrame(inputs, columns=FEATURES)
    probes = {'inputs': inputs.tolist(), 'labels': model.predict(X).tolist(), 'probabilities': model.predict_proba(X).tolist()}
    (ROOT / 'outputs/sgd_inference_probes.json').write_text(json.dumps(probes, indent=2, allow_nan=False)+'\n', encoding='utf-8')
    print('Verified all committed classifier metrics and confusion matrices; exported weights and 2,000 reference predictions.')
    print('Classes:', data['classes'], 'epochs:', data['iterations'])


if __name__ == '__main__':
    export()
